// ──────────────────────────────────────────────────────────────────────
// 歷史的章立て — Ritsuryō Provinces (大和) と Ryukyu Sanzan (琉球) の両系統
//
// 律令制下に設けられた旧国名(山城・丹波・丹後など)、今日の都道府県境とは
// 一致しないが、食材・言葉・産業・気候・神社の系統など、文化的枠組みとして
// 1,300 年生きている。例:京都府 = 山城・丹波・丹後の三国。
//
// 琉球三山(1322-1429)は律令制下になかった独立王国の名残で、本土とは別系統:
// 北山(山原)・中山(浦添→首里)・南山(大里) + 1500 年以降統合の先島(宮古・八重山)
// + 1900 年開拓の大東諸島(補章)。HistoricalProvince 型を共用し、ryukyu_sanzan
// strategy の章立てを駆動する。
//
// 都道府縣で organizing="ryoseikoku" / "ryukyu_sanzan" を指定したエリアは、
// 振興局(北海道専用)の代わりにこの歷史分けで章立てされる。
// ──────────────────────────────────────────────────────────────────────

export interface HistoricalProvince {
  /** 旧国名 / 三山名(漢字)*/
  name: string;
  /** romaji */
  romaji: string;
  /** 1-line cultural tagline — 食材・産業・風土を凝縮 */
  tagline: string;
  /** 1-character glyph — 章番号代わりの印として使う一字漢字 */
  glyph: string;
  /** 補章フラグ — 視覚的に降格される(沖縄の大東諸島など。1900 開拓・歷史浅) */
  supplementary?: boolean;
}

